create or replace function private.is_admin(
  allowed_roles text[] default array['owner','manager','editor']::text[]
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null
    and exists (
      select 1 from public.admin_users au
      where au.user_id = (select auth.uid())
        and au.active is true
        and au.role = any(allowed_roles)
    );
$$;
revoke all on function private.is_admin(text[]) from public;
grant execute on function private.is_admin(text[]) to authenticated;

