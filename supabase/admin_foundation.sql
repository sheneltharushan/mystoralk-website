create or replace function private.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  if to_jsonb(new) ? 'updated_by' then new.updated_by = (select auth.uid()); end if;
  return new;
end;
$$;
revoke all on function private.touch_updated_at() from public, anon, authenticated;

create or replace function private.record_admin_change()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  target_id text;
  payload jsonb;
begin
  if (select auth.uid()) is null then
    if tg_op = 'DELETE' then return old; else return new; end if;
  end if;
  target_id := coalesce(
    to_jsonb(new)->>'id', to_jsonb(old)->>'id',
    to_jsonb(new)->>'key', to_jsonb(old)->>'key',
    to_jsonb(new)->>'user_id', to_jsonb(old)->>'user_id'
  );
  payload := jsonb_strip_nulls(jsonb_build_object(
    'old', case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) else null end,
    'new', case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) else null end
  ));
  insert into public.audit_logs(actor_id, action, entity_type, entity_id, details)
  values ((select auth.uid()), lower(tg_op), tg_table_name, target_id, payload);
  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;
revoke all on function private.record_admin_change() from public, anon, authenticated;

